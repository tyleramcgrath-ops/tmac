"""Build the Teddy Midnight WordPress theme from the static redesign.

    python3 redesigns/teddy-headwear/wordpress/build_wp.py

The home, shop, studio and campaign markup comes straight from ../build.py, so the
theme and the static site stay identical. Links and image paths are rewritten to
WordPress helpers, the shared assets/site.css and assets/site.js are copied in, and
the result is written to wordpress/teddy-midnight/ plus wordpress/teddy-midnight.zip
(upload that zip in Appearance → Themes → Add New → Upload Theme).
"""
import re
import shutil
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SITE = HERE.parent
SRC = HERE / "src"
OUT = HERE / "teddy-midnight"
sys.path.insert(0, str(SITE))
import build  # noqa: E402  (the static site's page templates)


def php(html):
    """Swap static links and image paths for WordPress helpers."""
    html = re.sub(r'href="product-([a-z0-9-]+)\.html"', r'''href="<?php echo esc_url( teddy_product_url( '\1' ) ); ?>"''', html)
    html = re.sub(r'href="(shop|studio|campaign)\.html(?:#([a-z]+))?"',
                  lambda m: f'''href="<?php echo esc_url( teddy_url( '{m.group(1)}'{", '" + m.group(2) + "'" if m.group(2) else ""} ) ); ?>"''', html)
    html = re.sub(r'href="\./(?:#([a-z]+))?"',
                  lambda m: f'''href="<?php echo esc_url( teddy_url( 'home'{", '" + m.group(1) + "'" if m.group(1) else ""} ) ); ?>"''', html)
    html = re.sub(r'(src|data-img)="img/([^"]+)"', r'''\1="<?php echo esc_url( teddy_asset( 'img/\2' ) ); ?>"''', html)
    assert ".html" not in re.sub(r"https?://\S+", "", html), "unconverted static link"
    return html


def template(name, page, body, hero=False, header=""):
    return f"""<?php
/**{header}
 * Generated by wordpress/build_wp.py from the static redesign. Edit build.py, then rebuild.
 */
defined( 'ABSPATH' ) || exit;
teddy_body( array( 'page' => '{page}', 'hero' => {'true' if hero else 'false'} ) );
get_header();
?>
{body}
<?php
get_footer();
"""


def front_page():
    html = php(build.HOME)
    # Customizer: hero image, eyebrow and text.
    html = html.replace(
        '''<img src="<?php echo esc_url( teddy_asset( 'img/hero-noir.webp' ) ); ?>"''',
        '''<img src="<?php echo esc_url( teddy_hero_image() ); ?>"''', 1)
    html = html.replace(
        '<span class="eyebrow">Campaign 01 / Four cities, one frontier</span>',
        '''<span class="eyebrow"><?php echo esc_html( get_theme_mod( 'teddy_hero_eyebrow', 'Campaign 01 / Four cities, one frontier' ) ); ?></span>''', 1)
    sub = "Western silhouettes, contemporary monograms. 100% wool cowboy hats and fedoras, lined in gold silk, with your own letters on the crown."
    assert sub in html
    html = html.replace(sub, f'''<?php echo esc_html( get_theme_mod( 'teddy_hero_sub', '{sub}' ) ); ?>''', 1)
    return template("front-page", "home", html, hero=True, header="\n * Home page.")


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    shutil.copytree(SRC, OUT)
    (OUT / "assets" / "img").mkdir(parents=True, exist_ok=True)
    for f in ("site.css", "site.js"):
        shutil.copy(SITE / "assets" / f, OUT / "assets" / f)
    for img in (SITE / "img").glob("*.webp"):
        shutil.copy(img, OUT / "assets" / "img" / img.name)
    for extra in ("bear-favicon.png", "screenshot.jpg"):
        p = HERE / extra
        if p.exists():
            shutil.copy(p, OUT / (extra if extra.startswith("screenshot") else f"assets/img/{extra}"))

    (OUT / "front-page.php").write_text(front_page())
    (OUT / "page-templates").mkdir(exist_ok=True)
    (OUT / "page-templates" / "studio.php").write_text(
        template("studio", "studio", php(build.STUDIO), header="\n * Template Name: Monogram Studio"))
    (OUT / "page-templates" / "campaign.php").write_text(
        template("campaign", "campaign", php(build.CAMPAIGN), hero=True, header="\n * Template Name: Campaign"))
    (OUT / "woocommerce").mkdir(exist_ok=True)
    (OUT / "woocommerce" / "archive-product.php").write_text(
        template("shop", "shop", php(build.SHOP), header="\n * Shop and product category archives."))
    (OUT / "template-parts").mkdir(exist_ok=True)
    (OUT / "template-parts" / "intro.php").write_text(
        "<?php defined( 'ABSPATH' ) || exit; // The bear pops up (home page, once per visit). ?>\n" + build.INTRO.strip() + "\n")

    zpath = HERE / "teddy-midnight.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(OUT.rglob("*")):
            if f.is_file():
                z.write(f, Path("teddy-midnight") / f.relative_to(OUT))
    print(f"built {OUT.relative_to(SITE)} and {zpath.name} ({zpath.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
