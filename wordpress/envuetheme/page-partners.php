/* ── Partner quicknav active state on scroll ───────────────────── */
(function(){
  const btns = document.querySelectorAll('.partner-qnav-btn');
  const sections = Array.from(btns).map(b => document.querySelector(b.getAttribute('href')));
  const offset = 120;
  function activate(){
    let active = 0;
    sections.forEach((s,i)=>{if(s&&s.getBoundingClientRect().top<=offset)active=i;});
    btns.forEach((b,i)=>b.classList.toggle('active',i===active));
  }
  window.addEventListener('scroll',activate,{passive:true});
  activate();

  /* Smooth scroll */
  btns.forEach(b=>{
    b.addEventListener('click',e=>{
      e.preventDefault();
      const target = document.querySelector(b.getAttribute('href'));
      if(target){
        const y = target.getBoundingClientRect().top + window.scrollY - offset;
        window.scrollTo({top:y,behavior:'smooth'});
      }
    });
  });
})();
</script>
